// Builds the interface with Vite, embeds its files in the server and compiles
// one executable per platform into dist/.
//
//   bun scripts/build.ts                  all four targets
//   bun scripts/build.ts linux-x64        only the named targets
//   bun scripts/build.ts --release        refuses to build while a test key is accepted
//   bun scripts/build.ts --release --check-keys-only
//                                         only the key check, exit 1 when it fails
import { $ } from "bun";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";
import { verifyBuiltinManifest } from "../server/manifest/builtin.ts";
import { ACCEPTED_KEYS } from "../server/manifest/keys.ts";
import { releaseKeyProblems } from "../server/manifest/verify.ts";

const root = join(import.meta.dir, "..");
const webDist = join(root, "web", "dist");
const buildDir = join(root, "build");
const outDir = join(root, "dist");

// x64 targets use Bun's baseline build, which needs no AVX2. The interface
// must start on processors older than the engine's floor, so that the
// operator can still attach a remote engine.
const targets = [
  { name: "linux-x64", bunTarget: "bun-linux-x64-baseline", extension: "" },
  { name: "linux-arm64", bunTarget: "bun-linux-arm64", extension: "" },
  { name: "macos-arm64", bunTarget: "bun-darwin-arm64", extension: "" },
  { name: "windows-x64", bunTarget: "bun-windows-x64-baseline", extension: ".exe" },
];

async function listFiles(folder: string): Promise<string[]> {
  const entries = await readdir(folder, { withFileTypes: true, recursive: true });
  return entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name))
    .sort();
}

// Writes a module that imports every built file with { type: "file" }, so
// that `bun build --compile` embeds them and maps each URL path to its
// embedded file path.
async function writeAssetModule(files: string[]): Promise<void> {
  const imports: string[] = [];
  const entries: string[] = [];
  files.forEach((file, index) => {
    const fromBuild = relative(buildDir, file).split(sep).join("/");
    const urlPath = "/" + relative(webDist, file).split(sep).join("/");
    imports.push(`import asset${index} from ${JSON.stringify(fromBuild)} with { type: "file" };`);
    entries.push(`  [${JSON.stringify(urlPath)}, asset${index}],`);
  });
  const source = [
    "// Generated by scripts/build.ts. Do not edit.",
    ...imports,
    "",
    "export const assets: ReadonlyMap<string, string> = new Map([",
    ...entries,
    "]);",
    "",
  ].join("\n");
  await writeFile(join(buildDir, "assets.ts"), source);
}

async function writeEntry(): Promise<void> {
  const source = [
    "// Generated by scripts/build.ts. Do not edit.",
    'import { assets } from "./assets.ts";',
    'import { runFromCommandLine } from "../server/app/start.ts";',
    'import pkg from "../package.json";',
    "",
    "await runFromCommandLine(assets, pkg.version);",
    "",
  ].join("\n");
  await writeFile(join(buildDir, "entry.ts"), source);
}

const args = process.argv.slice(2);
const release = args.includes("--release");
const checkKeysOnly = args.includes("--check-keys-only");
const wanted = args.filter((arg) => !arg.startsWith("--"));
const unknownFlags = args.filter((arg) => arg.startsWith("--") && arg !== "--release" && arg !== "--check-keys-only");
if (unknownFlags.length > 0) {
  console.error(`Unknown flag: ${unknownFlags.join(", ")}. Known: --release, --check-keys-only`);
  process.exit(2);
}

// A release build must not carry the development test key. This runs before anything is built.
if (release) {
  const builtin = await verifyBuiltinManifest();
  const problems = releaseKeyProblems(ACCEPTED_KEYS, builtin.ok ? builtin.keyId : null);
  if (problems.length > 0) {
    console.error("A release build cannot go ahead:");
    for (const problem of problems) console.error(`- ${problem}`);
    process.exit(1);
  }
  console.log("Release key check passed.");
}
if (checkKeysOnly) process.exit(0);

const unknown = wanted.filter((name) => !targets.some((target) => target.name === name));
if (unknown.length > 0) {
  console.error(`Unknown target: ${unknown.join(", ")}. Known: ${targets.map((t) => t.name).join(", ")}`);
  process.exit(2);
}
const selected = wanted.length === 0 ? targets : targets.filter((t) => wanted.includes(t.name));

await $`bun x vite build`.cwd(root);
await rm(buildDir, { recursive: true, force: true });
await mkdir(buildDir, { recursive: true });
await mkdir(outDir, { recursive: true });
await writeAssetModule(await listFiles(webDist));
await writeEntry();

for (const target of selected) {
  const outfile = join(outDir, `aidm-ui-${target.name}${target.extension}`);
  await $`bun build --compile --minify --target=${target.bunTarget} ${join(buildDir, "entry.ts")} --outfile ${outfile}`.cwd(root);
  console.log(`Built ${relative(root, outfile)}`);
}
