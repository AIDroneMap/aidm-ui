import { expect, test } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { browserPath } from "../controls/browser-path.ts";
import { startBrowser } from "../controls/browser-start.ts";
import { findBrowserPage } from "../controls/browser-target.ts";

test("renders local tiles and supports keyboard and layer controls", async () => {
  const directory = await mkdtemp(join(tmpdir(), "aidm-map-"));
  const build = await Bun.build({ entrypoints: [new URL("./browser-fixture.tsx", import.meta.url).pathname], outdir: directory, naming: "fixture.[ext]", target: "browser", plugins: [{ name: "worker-url", setup(builder) {
    builder.onResolve({ filter: /maplibre-gl-worker\.mjs\?url$/ }, () => ({ path: "worker-url", namespace: "fixture" }));
    builder.onLoad({ filter: /.*/, namespace: "fixture" }, () => ({ contents: 'export default "/map-worker.mjs"', loader: "js" }));
  } }] });
  expect(build.success).toBe(true);
  const requests: string[] = [];
  let release: (() => void) | undefined;
  let markSlowRequest: (() => void) | undefined;
  const slowRequest = new Promise<void>(resolve => { markSlowRequest = resolve; });
  const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQI12P4z8DwHwAFAAH/cpxSZwAAAABJRU5ErkJggg==", "base64");
  const server = Bun.serve({ port: 0, hostname: "127.0.0.1", async fetch(request) {
    const path = new URL(request.url).pathname;
    requests.push(request.url);
    if (path === "/") return new Response('<link rel="stylesheet" href="/fixture.css"><div id="root"></div><script type="module" src="/fixture.js"></script>', { headers: { "content-type": "text/html", "content-security-policy": "default-src 'self'; img-src 'self' data: blob:; style-src 'self'; script-src 'self'; connect-src 'self'" } });
    if (path === "/fixture.js" || path === "/fixture.css") return new Response(Bun.file(join(directory, path.slice(1))));
    if (path === "/map-worker.mjs") return new Response(Bun.file("node_modules/maplibre-gl/dist/maplibre-gl-worker.mjs"), { headers: { "content-type": "text/javascript" } });
    if (path === "/api/settings/basemap") return Response.json({ enabled: false, url: "", scheme: "xyz", attribution: "" });
    if (path === "/api/runs/9/map") await new Promise<void>(resolve => { release = resolve; markSlowRequest?.(); });
    if (path.endsWith("/map")) return Response.json(path.includes("/8/") ? { state: "unavailable", layers: [] } : { state: "ready", layers: [{ name: "orthophoto", bounds: [-40, -40, 40, 40], minZoom: 0, maxZoom: 8, scheme: "xyz" }, { name: "surface", bounds: [-40, -40, 40, 40], minZoom: 0, maxZoom: 8, scheme: "tms" }] });
    if (path.includes("/tiles/")) return new Response(png, { headers: { "content-type": "image/png" } });
    return new Response(null, { status: 404 });
  } });
  let browser: Awaited<ReturnType<typeof startBrowser>> | undefined;
  let socket: WebSocket | undefined;
  try {
    browser = await startBrowser(await browserPath(), join(directory, "profile"), "about:blank");
    socket = new WebSocket((await findBrowserPage(Number(browser.port))).webSocketDebuggerUrl);
    await new Promise<void>((resolve, reject) => { socket!.onopen = () => resolve(); socket!.onerror = () => reject(new Error("Browser connection failed")); });
    let id = 0;
    const pending = new Map<number, (value: any) => void>();
    const urls: string[] = [];
    socket.onmessage = event => { const message = JSON.parse(String(event.data)); if (message.method === "Network.requestWillBeSent") urls.push(message.params.request.url); if (message.id) { pending.get(message.id)?.(message); pending.delete(message.id); } };
    const send = (method: string, params: object = {}) => new Promise<any>(resolve => { const next = ++id; pending.set(next, resolve); socket!.send(JSON.stringify({ id: next, method, params })); });
    const evaluate = async (expression: string) => { const result = await send("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true }); if (result.result.exceptionDetails) throw new Error(JSON.stringify(result.result.exceptionDetails)); return result.result.result.value; };
    const wait = (expression: string) => evaluate(`new Promise((resolve,reject) => { const end = Date.now()+10000; const check = () => ${expression} ? resolve(true) : Date.now()>end ? reject(new Error('condition timed out')) : setTimeout(check,20); check(); })`);
    await send("Network.enable");
    await send("Runtime.enable");
    await send("Page.navigate", { url: `http://127.0.0.1:${server.port}/` });
    await wait("document.querySelector('section button')");
    expect(requests.some(url => url.endsWith("/map"))).toBe(false);
    await evaluate("document.querySelector('section button').focus()");
    await send("Input.dispatchKeyEvent", { type: "keyDown", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    await send("Input.dispatchKeyEvent", { type: "keyUp", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    await wait("document.querySelector('.maplibregl-canvas') && document.body.textContent.includes('Map centre, latitude:')");
    await wait("performance.getEntriesByType('resource').some(entry => entry.name.includes('/tiles/'))");
    await wait("!document.querySelector('fieldset').disabled");
    expect(await evaluate("document.querySelectorAll('fieldset input').length")).toBe(2);
    expect(await evaluate("document.querySelectorAll('fieldset input')[1].checked")).toBe(false);
    await evaluate("document.querySelector('fieldset input').focus()");
    await send("Input.dispatchKeyEvent", { type: "keyDown", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    await send("Input.dispatchKeyEvent", { type: "keyUp", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    expect(await evaluate("document.querySelector('fieldset input').matches(':focus-visible')")).toBe(true);
    expect(await evaluate("document.querySelector('fieldset input').checked")).toBe(false);
    await evaluate("document.querySelectorAll('fieldset input')[1].focus()");
    await send("Input.dispatchKeyEvent", { type: "keyDown", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    await send("Input.dispatchKeyEvent", { type: "keyUp", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    expect(await evaluate("document.querySelectorAll('fieldset input')[1].checked")).toBe(true);

    const before = await evaluate("document.querySelector('p[aria-live]').textContent");
    await evaluate("document.querySelector('.maplibregl-canvas').focus()");
    await send("Input.dispatchKeyEvent", { type: "keyDown", key: "ArrowRight", code: "ArrowRight", windowsVirtualKeyCode: 39 });
    await send("Input.dispatchKeyEvent", { type: "keyUp", key: "ArrowRight", code: "ArrowRight", windowsVirtualKeyCode: 39 });
    await wait(`document.querySelector('p[aria-live]').textContent !== ${JSON.stringify(before)}`);
    const scaleBeforeZoom = await evaluate("document.querySelector('.maplibregl-ctrl-scale').textContent");
    const tilesBeforeZoom = requests.filter(url => url.includes("/tiles/")).length;
    await send("Input.dispatchKeyEvent", { type: "keyDown", key: "+", code: "Equal", windowsVirtualKeyCode: 187, modifiers: 8 });
    await send("Input.dispatchKeyEvent", { type: "keyUp", key: "+", code: "Equal", windowsVirtualKeyCode: 187, modifiers: 8 });
    await wait(`performance.getEntriesByType('resource').filter(entry => entry.name.includes('/tiles/')).length > ${tilesBeforeZoom}`);
    await wait(`document.querySelector('.maplibregl-ctrl-scale').textContent !== ${JSON.stringify(scaleBeforeZoom)}`);
    const zoomedScale = await evaluate("document.querySelector('.maplibregl-ctrl-scale').textContent");
    await send("Input.dispatchKeyEvent", { type: "keyDown", key: "-", code: "Minus", windowsVirtualKeyCode: 189 });
    await send("Input.dispatchKeyEvent", { type: "keyUp", key: "-", code: "Minus", windowsVirtualKeyCode: 189 });
    await wait(`document.querySelector('.maplibregl-ctrl-scale').textContent !== ${JSON.stringify(zoomedScale)}`);
    expect(await evaluate("!document.querySelector('[role=alert]')")).toBe(true);
    await evaluate("document.querySelectorAll('body > #root > button')[1].click()");
    await wait("document.querySelector('section button')");
    await evaluate("document.querySelector('section button').click()");
    await wait("document.querySelector('section [role=status]')?.textContent.includes('Loading the map')");
    await slowRequest;
    await evaluate("document.querySelectorAll('body > #root > button')[0].click()");
    await wait("document.querySelector('section button')");
    await evaluate("document.querySelector('section button').click()");
    await wait("document.querySelector('section [role=status]')?.textContent.includes('A map is not available')");
    release?.();
    await evaluate("new Promise(resolve => setTimeout(resolve, 100))");
    expect(await evaluate("!document.body.textContent.includes('Map centre, latitude:') && !document.querySelector('.maplibregl-canvas')")).toBe(true);
    await send("Page.reload");
    await wait("document.querySelector('section button')");
    expect(await evaluate("!document.querySelector('.maplibregl-canvas')")).toBe(true);
    await evaluate("document.querySelector('section button').click()");
    await wait("document.querySelector('.maplibregl-canvas')");
    expect(urls.filter(url => !url.startsWith("data:") && !url.startsWith("blob:")).every(url => url.startsWith(`http://127.0.0.1:${server.port}/`))).toBe(true);
    expect(requests.some(url => url.includes("/tiles/"))).toBe(true);
  } finally {
    release?.(); socket?.close(); await browser?.stop(); server.stop(true); await rm(directory, { recursive: true, force: true });
  }
}, 30000);
