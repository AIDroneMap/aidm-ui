import { expect, test } from "bun:test";
import { mkdtemp, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { openHarness, eventually } from "../../../server/testing/harness.ts";
import { assetsFromFolder } from "../../../server/http/static-assets.ts";
import { FakeTaskApi } from "../../../test-support/fake-task-api.ts";
import { browserPath } from "../controls/browser-path.ts";
import { startBrowser } from "../controls/browser-start.ts";
import { findBrowserPage } from "../controls/browser-target.ts";

test("run history, keyboard retry, changed settings and deletion use production routes", async () => {
  const folder = await mkdtemp(join(tmpdir(), "aidm-runs-browser-"));
  const publicFiles = join(folder, "public"), dataFolder = join(folder, "data");
  await mkdir(publicFiles); await mkdir(dataFolder);
  const build = await Bun.build({ entrypoints: [new URL("../pages/run-browser-fixture.tsx", import.meta.url).pathname], target: "browser", plugins: [{ name: "worker-url", setup(builder) {
    builder.onResolve({ filter: /draco_(wasm_wrapper\.js|decoder\.wasm)\?url$/ }, args => ({ path: args.path, namespace: "decoder-assets" }));
    builder.onLoad({ filter: /.*/, namespace: "decoder-assets" }, args => ({ contents: `export default ${JSON.stringify(`/decoder/${args.path.includes("wrapper") ? "draco_wasm_wrapper.js" : "draco_decoder.wasm"}`)}`, loader: "js" }));
    builder.onResolve({ filter: /maplibre-gl-worker\.mjs\?url$/ }, () => ({ path: "worker-url", namespace: "fixture" }));
    builder.onLoad({ filter: /.*/, namespace: "fixture" }, () => ({ contents: 'export default "/map-worker.mjs"', loader: "js" }));
  } }] });
  expect(build.success).toBe(true);
  for (const output of build.outputs) await Bun.write(join(publicFiles, output.path.endsWith(".css") ? "fixture.css" : "fixture.js"), output);
  await Bun.write(join(publicFiles, "index.html"), '<!doctype html><link rel="stylesheet" href="/fixture.css"><div id="root"></div><script type="module" src="/fixture.js"></script>');
  const assets = await assetsFromFolder(publicFiles);
  const engine = new FakeTaskApi({ info: { taskQueueCount: 7 } }); await engine.start();
  const other = new FakeTaskApi(); await other.start();
  const h = openHarness({ dataFolder, assets, runPollMs: 10 });
  h.settings.set("wizard.completed", true);
  const project = h.ctx.projects.create("Field", "").id;
  const firstEngine = h.engineStore.addRemote({ name: "Selected engine", address: engine.address, token: engine.token }).id;
  const nextEngine = h.engineStore.addRemote({ name: "Other engine", address: other.address, token: other.token }).id;
  const request = (method: string, path: string, body?: unknown) => fetch(h.base+path, { method, body: body === undefined ? undefined : JSON.stringify(body) });
  const bytes = Buffer.from("synthetic photo"), sha256 = createHash("sha256").update(bytes).digest("hex");
  const upload = await (await request("POST", `/api/projects/${project}/uploads`, { name: "photo.jpg", size: bytes.length, sha256 })).json() as { id: string };
  await fetch(h.base+`/api/projects/${project}/uploads/${upload.id}/chunks/0`, { method: "PUT", headers: { "x-chunk-sha256": sha256 }, body: bytes });
  await request("POST", `/api/projects/${project}/uploads/${upload.id}/complete`);
  const options = [{ name: "orthophoto-resolution", value: 6 }];
  const body = { engineId: firstEngine, preset: "quick-map", options };
  const review = await (await request("POST", `/api/projects/${project}/run-review`, body)).json() as any;
  const original = await (await request("POST", `/api/projects/${project}/runs`, { ...body, name: "Original", revision: review.revision })).json() as any;
  await eventually(async () => h.runs.get(original.id)?.state === "queued");
  const uuid = h.runs.get(original.id)!.taskUuid!;
  engine.setTask(uuid, { statusCode: 30, output: ["Original run log"] });
  await eventually(async () => h.runs.get(original.id)?.state === "failed");
  let browser: Awaited<ReturnType<typeof startBrowser>> | undefined, socket: WebSocket | undefined;
  const pending = new Map<number, { resolve(value: any): void; reject(error: Error): void; timer: Timer }>();
  try {
    browser = await startBrowser(await browserPath(), join(folder, "profile"), "about:blank");
    socket = new WebSocket((await findBrowserPage(Number(browser.port))).webSocketDebuggerUrl);
    await new Promise<void>((resolve,reject)=>{socket!.onopen=()=>resolve();socket!.onerror=()=>reject(new Error("browser connection"))});
    let next = 0;
    socket.onmessage = event => { const m = JSON.parse(String(event.data)), item = pending.get(m.id); if (!item) return; pending.delete(m.id); clearTimeout(item.timer); m.error ? item.reject(new Error(JSON.stringify(m.error))) : item.resolve(m.result); };
    const send = (method: string, params: object = {}) => new Promise<any>((resolve,reject)=>{const id=++next;const timer=setTimeout(()=>{pending.delete(id);reject(new Error(method+" timeout"))},10000);pending.set(id,{resolve,reject,timer});socket!.send(JSON.stringify({id,method,params}))});
    const evaluate = async (expression: string) => { const result = await send("Runtime.evaluate",{expression,returnByValue:true,awaitPromise:true}); if(result.exceptionDetails)throw new Error(JSON.stringify(result.exceptionDetails));return result.result.value; };
    const wait = (condition: string) => evaluate(`new Promise((resolve,reject)=>{const end=Date.now()+5000;const tick=()=>(${condition})?resolve(true):Date.now()>end?reject(Error(${JSON.stringify(condition)})):setTimeout(tick,20);tick()})`);
    const button = (label: string) => `[...document.querySelectorAll('button')].find(el=>el.textContent===${JSON.stringify(label)})`;
    const click = async (label: string) => { await wait(`${button(label)}&&!${button(label)}.disabled`);await evaluate(`${button(label)}.click();true`); };
    const field = async (selector: string, text: string) => { await wait(`document.querySelector(${JSON.stringify(selector)})`);await evaluate(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(el.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(text)});el.dispatchEvent(new Event('input',{bubbles:true}));return true})()`); };

    const activate = async (label: string) => {
      await wait(`${button(label)}&&!${button(label)}.disabled`);
      await evaluate(`${button(label)}.focus();true`);
      await send("Input.dispatchKeyEvent", { type: "keyDown", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
      await send("Input.dispatchKeyEvent", { type: "keyUp", key: " ", code: "Space", windowsVirtualKeyCode: 32 });
    };
    await send("Page.navigate", { url: h.base+`/#/projects/${project}` });
    await wait(`document.querySelector('a[href="#/runs/${original.id}"]')`);
    expect(await evaluate("document.body.textContent.includes('Selected engine')")).toBe(true);
    await field("#project-notes", "Keep these notes while the project refreshes");
    await evaluate("new Promise(resolve => requestAnimationFrame(() => resolve(true)))");
    expect(await evaluate("document.querySelectorAll('#run-history-title').length")).toBe(1);
    await evaluate(`location.hash='#/runs/${original.id}';true`);
    await activate("Run again with other settings");
    await wait("document.querySelector('.settings-editor')");
    expect(await evaluate("Number(document.querySelector('#run-engine').value)")).toBe(firstEngine);
    await field('.settings-editor input[id$="-search"]', "orthophoto-resolution");
    await wait("document.querySelector('.settings-editor-row input').value==='6'");
    await field(".settings-editor-row input", "8");
    await activate("Apply"); await activate("Start run");
    await wait(`location.hash!=='#/runs/${original.id}'&&document.body.textContent.includes('The engine reports 8 running or waiting runs')`);
    const changed = h.runs.latestForProject(project)!;
    expect(changed.taskUuid).toBe(uuid); expect(engine.uploads).toHaveLength(1);
    expect(changed.options).toContainEqual({ name: "orthophoto-resolution", value: 8 });
    expect(h.tracker.log(original.id,0).lines).toEqual(["Original run log"]);
    engine.setTask(uuid, { statusCode: 30 });
    await activate("Retry");
    await wait(`location.hash!=='#/runs/${changed.id}'&&document.body.textContent.includes('The engine reports 8 running or waiting runs')`);
    expect(engine.uploads).toHaveLength(1);
    await activate("Delete run");
    await wait("document.querySelector('dialog[open]')");
    await activate("Keep run"); expect(engine.tasks.size).toBe(1);
    await activate("Delete run"); await activate("Delete this run");
    await wait(`location.hash==='#/projects/${project}'&&document.querySelector('a[href="#/runs/${original.id}"]')`);
    expect(engine.tasks.size).toBe(0);
    await evaluate(`location.hash='#/runs/${original.id}';true`);
    await activate("Run again with other settings"); await wait("document.querySelector('.settings-editor')");
    await activate("Cancel");
    await evaluate(`document.querySelector('#run-engine').value='${nextEngine}';document.querySelector('#run-engine').dispatchEvent(new Event('change',{bubbles:true}));true`);
    await wait("document.body.textContent.includes('Engine: Other engine')");
    await activate("Start run");
    await eventually(async () => other.tasks.size===1&&[...other.tasks.values()][0]!.committed);
    expect(other.uploads).toHaveLength(1);
    expect(other.requests.some(request => request.path==='/task/restart')).toBe(false);
  } finally { for(const p of pending.values()){clearTimeout(p.timer);p.reject(new Error("test finished"))}socket?.close();await browser?.stop();await h.stop();await engine.stop();await other.stop();await rm(folder,{recursive:true,force:true}); }
},60000);
